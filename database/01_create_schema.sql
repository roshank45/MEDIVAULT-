-- Table 1: HOSPITAL
CREATE TABLE HOSPITAL (
    HOSPITAL_ID     NUMBER(10) PRIMARY KEY,
    NAME            VARCHAR2(150) NOT NULL,
    CODE            VARCHAR2(20) NOT NULL UNIQUE,
    ADDRESS         VARCHAR2(300) NOT NULL,
    CITY            VARCHAR2(100) NOT NULL,
    STATE           VARCHAR2(100) NOT NULL,
    PHONE           VARCHAR2(30) NOT NULL,
    EMAIL           VARCHAR2(100),
    IS_ACTIVE       NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_HOSPITAL_NAME UNIQUE (NAME),
    CONSTRAINT CHK_HOSPITAL_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

-- Table 2: APP_USER
CREATE TABLE APP_USER (
    USER_ID         NUMBER(10) PRIMARY KEY,
    HOSPITAL_ID     NUMBER(10),
    USERNAME        VARCHAR2(60) NOT NULL UNIQUE,
    PASSWORD_HASH   VARCHAR2(255) NOT NULL,
    FULL_NAME       VARCHAR2(120) NOT NULL,
    EMAIL           VARCHAR2(120) NOT NULL UNIQUE,
    PHONE           VARCHAR2(30),
    ROLE            VARCHAR2(30) NOT NULL,
    SPECIALTY       VARCHAR2(100),
    LICENSE_NUMBER  VARCHAR2(50),
    IS_ACTIVE       NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_USER_HOSPITAL FOREIGN KEY (HOSPITAL_ID) REFERENCES HOSPITAL(HOSPITAL_ID) ON DELETE SET NULL,
    CONSTRAINT UQ_USER_LICENSE UNIQUE (LICENSE_NUMBER),
    CONSTRAINT CHK_USER_ROLE CHECK (ROLE IN ('ADMIN', 'DOCTOR', 'PATIENT', 'EMERGENCY_CLINICIAN')),
    CONSTRAINT CHK_USER_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

-- Table 3: PATIENT
CREATE TABLE PATIENT (
    PATIENT_ID                  NUMBER(10) PRIMARY KEY,
    UNIQUE_PATIENT_ID           VARCHAR2(30) NOT NULL UNIQUE,
    USER_ID                     NUMBER(10),
    FIRST_NAME                  VARCHAR2(60) NOT NULL,
    LAST_NAME                   VARCHAR2(60) NOT NULL,
    DATE_OF_BIRTH               DATE NOT NULL,
    GENDER                      VARCHAR2(20) NOT NULL,
    BLOOD_GROUP                 VARCHAR2(20),
    PHONE                       VARCHAR2(30) NOT NULL,
    EMAIL                       VARCHAR2(120),
    ADDRESS                     VARCHAR2(300),
    EMERGENCY_CONTACT_NAME      VARCHAR2(120),
    EMERGENCY_CONTACT_PHONE     VARCHAR2(30),
    EMERGENCY_CONTACT_RELATION  VARCHAR2(60),
    ALLERGIES_RECORDED_STATUS   VARCHAR2(30) DEFAULT 'NOT_RECORDED' NOT NULL,
    CREATED_AT                  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT                  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_PATIENT_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER(USER_ID) ON DELETE SET NULL,
    CONSTRAINT UQ_PATIENT_PHONE UNIQUE (PHONE),
    CONSTRAINT UQ_PATIENT_NAME_DOB UNIQUE (FIRST_NAME, LAST_NAME, DATE_OF_BIRTH),
    CONSTRAINT CHK_PATIENT_GENDER CHECK (GENDER IN ('MALE', 'FEMALE', 'OTHER')),
    CONSTRAINT CHK_ALLERGY_STATUS CHECK (ALLERGIES_RECORDED_STATUS IN ('NOT_RECORDED', 'NO_KNOWN_ALLERGIES', 'DOCUMENTED'))
);

-- Table 4: PATIENT_ACCESS (Role & Break-Glass Audit Control)
CREATE TABLE PATIENT_ACCESS (
    ACCESS_ID       NUMBER(10) PRIMARY KEY,
    PATIENT_ID      NUMBER(10) NOT NULL,
    USER_ID         NUMBER(10) NOT NULL,
    HOSPITAL_ID     NUMBER(10) NOT NULL,
    ACCESS_TYPE     VARCHAR2(30) NOT NULL,
    REASON          VARCHAR2(300) NOT NULL,
    IS_BREAK_GLASS  NUMBER(1) DEFAULT 0 NOT NULL,
    GRANTED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    EXPIRES_AT      TIMESTAMP,
    CONSTRAINT FK_ACCESS_PATIENT FOREIGN KEY (PATIENT_ID) REFERENCES PATIENT(PATIENT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_ACCESS_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER(USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_ACCESS_HOSPITAL FOREIGN KEY (HOSPITAL_ID) REFERENCES HOSPITAL(HOSPITAL_ID) ON DELETE CASCADE,
    CONSTRAINT UQ_PATIENT_ACCESS_EVENT UNIQUE (PATIENT_ID, USER_ID, GRANTED_AT),
    CONSTRAINT CHK_ACCESS_TYPE CHECK (ACCESS_TYPE IN ('ROUTINE_CARE', 'EMERGENCY_BREAK_GLASS', 'PATIENT_CONSENT', 'REFERRAL')),
    CONSTRAINT CHK_IS_BREAK_GLASS CHECK (IS_BREAK_GLASS IN (0, 1))
);

