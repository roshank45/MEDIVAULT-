BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE AUDIT_LOG ADD (AUDIT_UUID VARCHAR2(64) DEFAULT SYS_GUID() NOT NULL)';
  DBMS_OUTPUT.PUT_LINE('[+] Added AUDIT_UUID column to AUDIT_LOG');
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE = -01430 THEN
      DBMS_OUTPUT.PUT_LINE('[INFO] AUDIT_UUID column already exists in AUDIT_LOG');
