      DBMS_OUTPUT.PUT_LINE('[WARN] AUDIT_UUID: ' || SQLERRM);
    END IF;
END;
/

-- 3. HELPER PL/SQL BLOCK TO SAFELY ADD CONSTRAINTS
CREATE OR REPLACE PROCEDURE ADD_CONSTRAINT_SAFE (
    p_table      IN VARCHAR2,
    p_cname      IN VARCHAR2,
    p_clause     IN VARCHAR2
) IS
BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD CONSTRAINT ' || p_cname || ' ' || p_clause;
    DBMS_OUTPUT.PUT_LINE('[+] Applied constraint ' || p_cname || ' on ' || p_table);
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE IN (-02260, -02261, -02264, -02275) THEN
            DBMS_OUTPUT.PUT_LINE('[INFO] Constraint ' || p_cname || ' already exists on ' || p_table);
        ELSE
            DBMS_OUTPUT.PUT_LINE('[ERROR] Failed on ' || p_cname || ': ' || SQLERRM);
        END IF;
END;
/

