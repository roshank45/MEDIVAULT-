-- 1. VIEW: Patient Active Medications (Mandatory requirement in prompt)
CREATE OR REPLACE VIEW VW_ACTIVE_PATIENT_MEDICATIONS AS
SELECT 
    p.PATIENT_ID,
    p.UNIQUE_PATIENT_ID,
    p.FIRST_NAME || ' ' || p.LAST_NAME AS PATIENT_NAME,
    p.DATE_OF_BIRTH,
    rx.PRESCRIPTION_ID,
    rx.PRESCRIPTION_CODE,
    rxi.ITEM_ID,
    m.MEDICINE_ID,
    m.BRAND_NAME,
    m.GENERIC_NAME,
    m.DRUG_CLASS,
    rxi.DOSE_AMOUNT || ' ' || rxi.DOSE_UNIT AS DOSAGE,
    rxi.FREQUENCY,
    rxi.ROUTE,
    rxi.DURATION_DAYS,
    rxi.INSTRUCTIONS,
    rxi.START_DATE,
    rxi.END_DATE,
    rxi.STATUS AS ITEM_STATUS,
    rx.STATUS AS RX_STATUS,
    doc.FULL_NAME AS PRESCRIBING_DOCTOR,
    doc.SPECIALTY AS DOCTOR_SPECIALTY,
    h.HOSPITAL_ID,
    h.NAME AS HOSPITAL_NAME,
    rx.CREATED_AT AS PRESCRIBED_AT
FROM PRESCRIPTION rx
JOIN PATIENT p ON rx.PATIENT_ID = p.PATIENT_ID
JOIN PRESCRIPTION_ITEM rxi ON rx.PRESCRIPTION_ID = rxi.PRESCRIPTION_ID
JOIN MEDICINE m ON rxi.MEDICINE_ID = m.MEDICINE_ID
JOIN APP_USER doc ON rx.DOCTOR_ID = doc.USER_ID
JOIN HOSPITAL h ON rx.HOSPITAL_ID = h.HOSPITAL_ID
WHERE rx.STATUS = 'ACTIVE' 
  AND rxi.STATUS = 'ACTIVE'
  AND (rxi.END_DATE >= TRUNC(SYSDATE) OR rxi.END_DATE IS NULL);

-- 2. VIEW: Longitudinal Patient Timeline Summary Across Participating Hospitals
CREATE OR REPLACE VIEW VW_PATIENT_TIMELINE_SUMMARY AS
SELECT 
    v.VISIT_ID,
    v.PATIENT_ID,
    p.UNIQUE_PATIENT_ID,
    p.FIRST_NAME || ' ' || p.LAST_NAME AS PATIENT_NAME,
    v.VISIT_DATE,
    v.VISIT_TYPE,
    v.CHIEF_COMPLAINT,
    v.CLINICAL_NOTES,
    h.HOSPITAL_ID,
    h.NAME AS HOSPITAL_NAME,
    h.CODE AS HOSPITAL_CODE,
    doc.USER_ID AS DOCTOR_ID,
    doc.FULL_NAME AS DOCTOR_NAME,
    doc.SPECIALTY AS DOCTOR_SPECIALTY,
    (SELECT COUNT(*) FROM VISIT_DIAGNOSIS vd WHERE vd.VISIT_ID = v.VISIT_ID) AS DIAGNOSIS_COUNT,
    (SELECT COUNT(*) FROM PRESCRIPTION pr WHERE pr.VISIT_ID = v.VISIT_ID) AS PRESCRIPTION_COUNT,
    (SELECT COUNT(*) FROM VITAL_RECORD vr WHERE vr.VISIT_ID = v.VISIT_ID) AS VITALS_RECORDED_COUNT,
    (SELECT COUNT(*) FROM MEDICAL_TEST mt WHERE mt.VISIT_ID = v.VISIT_ID) AS TESTS_ORDERED_COUNT
FROM VISIT v
JOIN PATIENT p ON v.PATIENT_ID = p.PATIENT_ID
JOIN HOSPITAL h ON v.HOSPITAL_ID = h.HOSPITAL_ID
JOIN APP_USER doc ON v.DOCTOR_ID = doc.USER_ID;

-- 3. VIEW: Multi-Hospital Activity Metrics
CREATE OR REPLACE VIEW VW_HOSPITAL_ACTIVITY_METRICS AS
SELECT 
    h.HOSPITAL_ID,
    h.NAME AS HOSPITAL_NAME,
    h.CODE AS HOSPITAL_CODE,
    COUNT(DISTINCT v.VISIT_ID) AS TOTAL_VISITS,
    COUNT(DISTINCT v.PATIENT_ID) AS UNIQUE_PATIENTS_SEEN,
    COUNT(DISTINCT rx.PRESCRIPTION_ID) AS TOTAL_PRESCRIPTIONS_ISSUED,
    COUNT(DISTINCT mt.TEST_ID) AS TOTAL_TESTS_ORDERED,
    MAX(v.VISIT_DATE) AS LAST_RECORDED_ACTIVITY
FROM HOSPITAL h
LEFT JOIN VISIT v ON h.HOSPITAL_ID = v.HOSPITAL_ID
LEFT JOIN PRESCRIPTION rx ON h.HOSPITAL_ID = rx.HOSPITAL_ID
LEFT JOIN MEDICAL_TEST mt ON h.HOSPITAL_ID = mt.HOSPITAL_ID
GROUP BY h.HOSPITAL_ID, h.NAME, h.CODE;

-- 4. VIEW: Patient Documented Allergies Overview
CREATE OR REPLACE VIEW VW_PATIENT_ALLERGIES_OVERVIEW AS
SELECT 
    a.ALLERGY_ID,
    p.PATIENT_ID,
    p.UNIQUE_PATIENT_ID,
    p.FIRST_NAME || ' ' || p.LAST_NAME AS PATIENT_NAME,
    a.ALLERGEN_NAME,
    a.ALLERGEN_TYPE,
    a.REACTION,
    a.SEVERITY,
    a.STATUS,
    a.RECORDED_AT,
    doc.FULL_NAME AS RECORDED_BY_DOCTOR
FROM ALLERGY a
JOIN PATIENT p ON a.PATIENT_ID = p.PATIENT_ID
JOIN APP_USER doc ON a.RECORDED_BY = doc.USER_ID;
